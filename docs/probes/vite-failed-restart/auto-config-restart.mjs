import assert from 'node:assert/strict';
import { mkdtemp, readFile, realpath, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { setTimeout as delay } from 'node:timers/promises';
import { createLogger, createServer, version } from '/Users/dinh-van.colomban/Workspace/private/devkit-extension/node_modules/vite/dist/node/index.js';
import { defineService } from '/Users/dinh-van.colomban/Workspace/private/devkit-extension/packages/core/dist/index.js';
import { counterCapability } from '/Users/dinh-van.colomban/Workspace/private/devkit-extension/examples/contribution/dist/index.js';
import { counterService } from '/Users/dinh-van.colomban/Workspace/private/devkit-extension/examples/server-contexts/dist/index.js';
import { serverExecution } from '/Users/dinh-van.colomban/Workspace/private/devkit-extension/packages/server/dist/index.js';
import { providerFromVite } from '/Users/dinh-van.colomban/Workspace/private/devkit-extension/examples/vite-hosts/dist/index.js';
const results = { vite: version, node: process.version, cases: [] };
for (const host of ['devframe', 'devtools']) {
  const directory = await realpath(await mkdtemp(join(tmpdir(), 'devkit-failed-restart-')));
  const configFile = join(directory, 'vite.config.mts');
  const clientFile=join(directory,'client.js');
  await writeFile(clientFile,'export const value = 1;\n');
  globalThis.__devkitProbe = { servers: [], events: [], watcherErrors: [] };
  const loggedErrors=[];
  const logger=createLogger('silent');
  logger.error=(error)=>{loggedErrors.push(String(error));};
  await writeFile(configFile, `import { counterHostPlugins } from '/Users/dinh-van.colomban/Workspace/private/devkit-extension/examples/vite-hosts/dist/index.js';
export default async () => ({plugins: [{name:'candidate-trace',configureServer(server){const generation=globalThis.__devkitProbe.servers.length+1;globalThis.__devkitProbe.servers.push(server);server.watcher.on('error',error=>globalThis.__devkitProbe.watcherErrors.push(String(error)));globalThis.__devkitProbe.events.push('configure:'+generation);},closeServer({reason}){globalThis.__devkitProbe.events.push('close:'+reason);}},...await counterHostPlugins('${host}')]});\n`);
  const server = await createServer({root:directory,configFile,logLevel:'silent',customLogger:logger,publicDir:false,server:{host:'127.0.0.1',port:0,watch:{},hmr:true},optimizeDeps:{noDiscovery:true,include:[]}});
  let candidate;
  try {
    await server.listen();
    const provider = await providerFromVite(server);
    await provider.services.replace(provider.startup.services[0].handle, defineService(counterCapability, {id:'example.failed-restart',execution:serverExecution,setup(context){ context.scope.onDispose(() => {throw new Error('Cleanup probe sentinel');});return counterService.setup(context);}}));
    const oldConfig = server.config;
    for(let attempt=0;attempt<100 && !Object.hasOwn(server.watcher.getWatched(),directory);attempt+=1) await delay(10);
    assert.ok(Object.hasOwn(server.watcher.getWatched(),directory));
    await writeFile(configFile,(await readFile(configFile,'utf8'))+'// watched config edit\n');
    for(let attempt=0;attempt<500 && !loggedErrors.some(message=>message.includes('Provider cleanup is blocked'));attempt+=1) await delay(10);
    assert.ok(loggedErrors.some(message=>message.includes('Provider cleanup is blocked')));
    const rejection='caught and logged by native Vite config update path';
    candidate=globalThis.__devkitProbe.servers[1];
    assert.ok(candidate);
    assert.equal(server.config,oldConfig);
    let candidateReadiness='pending';
    providerFromVite(candidate).then(() => {candidateReadiness='resolved'}, () => {candidateReadiness='rejected'});
    await Promise.resolve();
    for(let attempt=0;attempt<100 && !Object.hasOwn(candidate.watcher.getWatched(),directory);attempt+=1) await delay(10);
    assert.ok(Object.hasOwn(candidate.watcher.getWatched(),directory));
    let candidateObservedChange=false;
    candidate.watcher.on('change', path => {if(path===clientFile) candidateObservedChange=true;});
    await writeFile(clientFile,'export const value = 2;\n');
    for(let attempt=0;attempt<100 && !candidateObservedChange;attempt+=1) await delay(10);
    assert.ok(candidateObservedChange);
    const beforeManualClose={events:[...globalThis.__devkitProbe.events],candidateObservedChange,watchedDirectoryCount:Object.keys(candidate.watcher.getWatched()).length,oldListening:server.httpServer.listening,candidateListening:candidate.httpServer.listening,candidateWatcherClosed:candidate.watcher.closed,candidateReadiness,candidateListeningCallbacks:candidate.httpServer.listenerCount('listening')};
    assert.equal(candidateReadiness,'pending');
    assert.equal(globalThis.__devkitProbe.events.filter(event=>event.startsWith('close')).length,1);
    await candidate.close();
    await Promise.resolve();
    const afterManualClose={events:[...globalThis.__devkitProbe.events],watchedDirectoryCount:Object.keys(candidate.watcher.getWatched()).length,candidateWatcherClosed:candidate.watcher.closed,candidateReadiness,candidateListeningCallbacks:candidate.httpServer.listenerCount('listening')};
    assert.equal(candidateReadiness,'rejected');
    assert.ok(afterManualClose.candidateListeningCallbacks < beforeManualClose.candidateListeningCallbacks);
    assert.deepEqual(globalThis.__devkitProbe.watcherErrors,[]);
    results.cases.push({host,rejection,loggedErrors,watcherErrors:globalThis.__devkitProbe.watcherErrors,processContinuedAfterConfigFailure:true,beforeManualClose,afterManualClose});
  } finally {
    await candidate?.close().catch(()=>{});
    await server.close().catch(()=>{});
    await rm(directory,{recursive:true,force:true});
  }
}
console.info(JSON.stringify(results,null,2));
